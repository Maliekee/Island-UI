using System;
using System.Collections.Generic;

namespace IslandUI
{
    // Which containers the reach pool may hold, and what we owe the game after
    // writing one (docs/window-system.md §6.15, D38/D39).
    //
    // THE AXIS IS THE ENGINE, NOT THE TYPE. `InventorySlot.Type` has 31 entries
    // and none of them names the thing that decides this, which is what turns a
    // container's contents into gameplay. A trap, a planter and a plain wooden
    // chest are all `Type.None`; the first two drive their props through a poll
    // over the vanilla panel's mirror grid and the third has no machinery at all.
    // Type could never have separated them, which is why the two open-coded type
    // tests this replaces were wrong from the day they were written.
    //
    // Not derived from `IsPlainStorage` either, and that was the first design.
    // The census disproved the nesting in both directions at once:
    // a breed prop keeps VANILLA's panel yet is pool-safe once D39 runs its
    // callback, and a treasure chest is ours to intercept yet is NOT pool-safe,
    // because its loot is generated by `TreasureSet` on first open and the pool
    // never opens anything. Two questions, correlated and independent.
    internal static class ContainerPolicy
    {
        internal enum Engine
        {
            // The slots ARE the state. Nothing watches them, so a write from
            // anywhere is complete the moment it lands.
            Inert,
            // `InventoryManager.BreedInventory()` polls the MIRROR slots while the
            // vanilla panel is open and calls TrapLoad / PetCheck / PlanterCheck /
            // FarmCheck for each slot that changed. Those calls are the half that
            // puts the NPC in the cage, plants the seed, sets the bait.
            Breed,
            // `InventoryManager.RackInventory()` does the same for fourteen prop
            // types, dispatching to a *Check per type (InventoryManager.cs:994).
            Rack,
            // Vanilla moves a bench's strip into the mirror and CONSUMES from
            // there. Safe only while the bench redirect keeps craftPanelID at 0.
            Bench,
            // Loot generated by TreasureScript.TreasureSet on first open.
            Treasure,
            // The panel is a launcher: the slots hold state but the interaction
            // runs a coroutine or raises a prop panel.
            Prop,
        }

        // BreedInventory's switch verbatim (InventoryManager.cs:889). The SEVEN,
        // not "anything carrying a BreedInfo" — widening this has already been
        // paid for once, and the census shows why the narrow list is right: the
        // harvest box and the mine both carry a BreedInfo (Harvest, Stone) that
        // no poll anywhere reads, so both are plain storage and always were.
        private static bool PolledBreed(BreedInfo.BreedType t)
        {
            switch (t)
            {
                case BreedInfo.BreedType.Trap:
                case BreedInfo.BreedType.Planter:
                case BreedInfo.BreedType.Pet:
                case BreedInfo.BreedType.Egg:
                case BreedInfo.BreedType.Mushroom:
                case BreedInfo.BreedType.Beehive:
                case BreedInfo.BreedType.Herb:
                    return true;
            }
            return false;
        }

        // RackInventory's dispatch list (InventoryManager.cs:994), plus Rack
        // itself: Rack is in the LOAD switch that starts the coroutine, and
        // starting it is what makes the mirror load-bearing.
        private static bool PolledRack(InventorySlot.Type t)
        {
            switch (t)
            {
                case InventorySlot.Type.Rack:
                case InventorySlot.Type.Pole:
                case InventorySlot.Type.Toilet:
                case InventorySlot.Type.Dye:
                case InventorySlot.Type.Restrain:
                case InventorySlot.Type.GlassTank:
                case InventorySlot.Type.BodyRack:
                case InventorySlot.Type.ShowCase:
                case InventorySlot.Type.Table:
                case InventorySlot.Type.Capsule:
                case InventorySlot.Type.Milk:
                case InventorySlot.Type.ItemStand:
                case InventorySlot.Type.Picture:
                case InventorySlot.Type.Core:
                    return true;
            }
            return false;
        }

        // Vanilla's own list of the Type.Edit props that carry storage
        // (UIManager.cs:2131): the two closets, named by key because the type is
        // shared with the mirror and the surgery bed, which hold nothing. Their
        // dress-up runs off the prop panel and never reads these slots.
        internal static bool IsCloset(InventorySlot c)
        {
            if (c == null || c.type != InventorySlot.Type.Edit)
            {
                return false;
            }
            var info = c.GetComponent<ItemInfo>();
            return info != null
                && (info.itemKey == "closet_spider" || info.itemKey == "closet_pretty");
        }

        // THE MIRROR IS THE MECHANISM, SO THE MIRROR STAYS. A rack prop keeps
        // vanilla's own load - its contents into slots 50+, RackInventory polling
        // them, the prop's *Check firing on a change, and every one of the game's
        // 28 direct itemSlot[50+] reads left exactly as written - and what changes
        // is only the VIEW: the panel is hidden and our focus plate draws the
        // mirror through Resolve, as it already does for a targeted character's
        // bag. A write from one of our cells lands in the mirror slot itself,
        // which is what the poll diffs, so ToiletCheck and the rest run as they
        // always did. Nothing is re-implemented and nothing needs unmasking.
        //
        // Per type, so each can be PLAYED before the next goes on: the
        // failure mode of a missed reader is silent, and attribution is what a
        // one-at-a-time list buys. Not the pool: PoolEligible still says no, a
        // rack is a thing you act on, not a thing you peek into.
        private static readonly HashSet<InventorySlot.Type> RackList = new HashSet<InventorySlot.Type>
        {
            InventorySlot.Type.Toilet,
            InventorySlot.Type.ShowCase,
            InventorySlot.Type.BodyRack,
            InventorySlot.Type.Milk,
        };

        internal static bool IsViewedRack(InventorySlot c)
        {
            return c != null && PolledRack(c.type) && RackList.Contains(c.type);
        }

        // A planter's cell takes one seed, placed only by hand (InventoryWindow.PlantOne)
        internal static bool IsPlanter(InventorySlot c)
        {
            var breed = c != null ? c.GetComponent<BreedInfo>() : null;
            return breed != null && breed.breedType == BreedInfo.BreedType.Planter;
        }

        internal static Engine EngineOf(InventorySlot container)
        {
            if (container == null)
            {
                return Engine.Inert;
            }
            // Order matters: a breed prop is Type.None, so the type test below
            // would call it inert. The component is the more specific fact.
            var breed = container.GetComponent<BreedInfo>();
            if (breed != null && PolledBreed(breed.breedType))
            {
                return Engine.Breed;
            }
            if (PolledRack(container.type))
            {
                return Engine.Rack;
            }
            switch (container.type)
            {
                case InventorySlot.Type.Bench:
                    return Engine.Bench;
                case InventorySlot.Type.Treasure:
                    return Engine.Treasure;
                case InventorySlot.Type.None:
                case InventorySlot.Type.Material:
                // the collector's act only adds flesh through ItemToChest; its
                // slots are a bag like any chest's
                case InventorySlot.Type.FleshCollector:
                    return Engine.Inert;
                // a closet's twenty slots are as inert as a chest's; the mirror
                // and the surgery bed share the type and stay props
                case InventorySlot.Type.Edit:
                    return IsCloset(container) ? Engine.Inert : Engine.Prop;
            }
            return Engine.Prop;
        }

        // What a container is FOR, which is the axis a person filters on. The
        // engine answers "can a write be made whole" and is about mechanism; this
        // answers "is this the kind of thing I want to see" and is about intent.
        // They are deliberately separate types: one is a safety fact and the
        // other is a preference, and a single enum serving both would be one
        // step from a preference switching off a safety gate (D41).
        internal enum Family
        {
            // Type.Material - the storages a workbench counts as its own stock.
            Materials,
            // Everything else inert: wooden chests, boxes, the mine's output.
            Chests,
            // Workbenches, whose ten-slot strip is real storage.
            Benches,
            // The polled breed props. The game's own word for them is `breed`,
            // and borrowing it beats inventing one - a cage, a planter, a hive
            // and a trap have no common name in English but they do in the code.
            Breeding,
            // The bags of the people you employ (window-system.md
            // D35's second scan). Never a sweep's destination: a person's bag is
            // theirs, so the family is shown or hidden and nothing more.
            Bags,
            // The pockets of the downed and the dead who are not yours, so enemy
            // corpses can be looted from the vicinity window - the bodies the
            // game's own click would search.
            // Shown or hidden, like Bags: moved by hand, never swept.
            Bodies,
            // Not filterable yet: benches, treasure, racks, props. They are not
            // in the pool at all, so there is nothing for a box to turn off.
            Other,
        }

        // THREE STATES, not two. "Do I want to see it" and
        // "may a sweep dump things into it" are different questions, and binding
        // them to one switch is what made D24 a compiled-in law instead of a
        // default: quick-stack targeted material storages only, because that was
        // the one family anyone would want it to target, and there was nowhere to
        // say so per family.
        //
        // The distinction is the same one D39 and D41 already turn on. Placing an
        // item by hand is a DELIBERATE act about one container; a sweep is not
        // about any container. A family can be worth looking at and still be the
        // wrong place for something to land in unattended - a planter most of
        // all, where Stack would mean "plant these seeds".
        internal enum FamilyMode
        {
            Hidden,
            Show,
            Stack,
        }

        internal static FamilyMode Mode(Family f)
        {
            FamilyMode mode = FamilyMode.Show;
            switch (f)
            {
                case Family.Materials: mode = Settings.ReachMaterials.Value; break;
                case Family.Chests: mode = Settings.ReachChests.Value; break;
                case Family.Breeding: mode = Settings.ReachBreeding.Value; break;
                case Family.Benches: mode = Settings.ReachBenches.Value; break;
                case Family.Bags: mode = Settings.ReachBags.Value; break;
                case Family.Bodies: mode = Settings.ReachBodies.Value; break;
            }
            // a Stack left in the .cfg for a family that no longer offers it
            // reads as shown
            return mode == FamilyMode.Stack && !CanStack(f) ? FamilyMode.Show : mode;
        }

        // Whether a family may be the sweep's destination at all. Bags never
        // were; breeding props stopped being: a sweep is a bulk
        // write, and BulkSafe says why that cannot be made whole there.
        internal static bool CanStack(Family f)
        {
            return f != Family.Bags && f != Family.Bodies && f != Family.Breeding;
        }

        // Hidden -> Show -> Stack -> Hidden. One click, one step, and the cycle
        // reads outward: less visible to more involved. Bags skip Stack, and so
        // does every family while no quick-stack key is bound - Stack is the
        // sweep's destination and nothing else, so with no sweep it is a state
        // that does nothing (the key is unbound by default).
        internal static bool SweepBound => Settings.QuickStackKey.Value != UnityEngine.KeyCode.None;

        internal static void Cycle(Family f)
        {
            FamilyMode next = Mode(f) == FamilyMode.Hidden ? FamilyMode.Show
                : Mode(f) == FamilyMode.Show && CanStack(f) && SweepBound ? FamilyMode.Stack
                : FamilyMode.Hidden;
            SetMode(f, next);
        }

        // Set outright: the settings window's dropdown names the state rather
        // than stepping to it. BepInEx writes the .cfg on set.
        internal static void SetMode(Family f, FamilyMode mode)
        {
            if (mode == FamilyMode.Stack && !CanStack(f))
            {
                mode = FamilyMode.Show;
            }
            switch (f)
            {
                case Family.Materials: Settings.ReachMaterials.Value = mode; break;
                case Family.Chests: Settings.ReachChests.Value = mode; break;
                case Family.Breeding: Settings.ReachBreeding.Value = mode; break;
                case Family.Benches: Settings.ReachBenches.Value = mode; break;
                case Family.Bags: Settings.ReachBags.Value = mode; break;
                case Family.Bodies: Settings.ReachBodies.Value = mode; break;
            }
        }

        // A quick-stack destination. Stack IMPLIES shown: a sweep that fills a
        // container you cannot see is the automatic destination this project
        // already refused once ("a rule you cannot see and cannot undo").
        internal static bool FamilyStacks(Family f)
        {
            return CanStack(f) && Mode(f) == FamilyMode.Stack;
        }

        // A character's bag is a colliderless child of the character, which is
        // vanilla's own test for it (VanillaContainerUI.IsCharacterBag's shape).
        internal static bool IsCharacterBag(InventorySlot c)
        {
            return c != null && c.transform.parent != null
                && c.transform.parent.GetComponent<CommonStates>() != null;
        }

        // A body's pockets: a character bag whose owner is down or dead
        // (ReachRule.Body) and is not one of your people - yours stay Bags,
        // downed or not.
        internal static bool IsBodyBag(InventorySlot c)
        {
            CommonStates owner = IsCharacterBag(c) ? c.transform.parent.GetComponent<CommonStates>() : null;
            return owner != null && ReachRule.Body(owner)
                && owner.employ != CommonStates.Employ.Friend && owner.employ != CommonStates.Employ.Favorite;
        }

        // What the vicinity window's All in · Stack · All out may write: plain
        // storage only. A planter, a cage, a bench strip and a person's bag are
        // listed for looking and for moving by hand, never for a bulk move.
        internal static bool BulkTarget(InventorySlot c)
        {
            Family f = FamilyOf(c);
            return BulkSafe(c) && (f == Family.Materials || f == Family.Chests) && FamilyShown(f);
        }

        // ALL OUT TAKES THE HARVEST (fish traps holding fish are
        // listed in the vicinity, and All out left them). A breeding prop is no bulk
        // move's to write (BulkSafe, below) - but taking its harvest out is a write
        // the game makes itself: the Harvest job (NPCManager.cs:6238) picks a slot by
        // HarvestableCheck, takes one, and calls the prop's callback. So All out may
        // take what that job may take, from where it takes it, and calls what it
        // calls (AfterHarvest). Honey, herbs, eggs, mushrooms, fish - never a seed, a
        // captive or a hen. Nothing is put INTO these: All in and Stack still stop at
        // BulkTarget.
        internal static bool HarvestSource(InventorySlot c)
        {
            if (c == null || c.slots == null || IsWrecked(c) || EngineOf(c) != Engine.Breed
                || !FamilyShown(Family.Breeding))
            {
                return false;
            }
            var info = c.GetComponent<ItemInfo>();
            switch (info != null ? info.itemKey : null)
            {
                case "farm_beehive_01":
                case "farm_herb_01":
                case "farm_herb_02":
                case "farm_poultry_01":
                case "farm_mushroom_01":
                case "trap_fish_01":
                    return true;
            }
            return false;
        }

        // HarvestableCheck's rule for one slot, verbatim (NPCManager.cs:5506)
        internal static bool IsHarvest(InventorySlot c, string itemKey)
        {
            if (string.IsNullOrEmpty(itemKey))
            {
                return false;
            }
            var info = c.GetComponent<ItemInfo>();
            switch (info != null ? info.itemKey : null)
            {
                case "farm_beehive_01":
                case "farm_herb_01":
                case "farm_herb_02":
                case "farm_poultry_01":
                    return itemKey == "food_honey_01" || itemKey == "herb_01" || itemKey == "herb_02"
                        || itemKey == "food_egg_01" || itemKey == "food_egg_02";
                case "farm_mushroom_01":
                    return itemKey.StartsWith("mushroom");
                case "trap_fish_01":
                    return itemKey.StartsWith("fish");
            }
            return false;
        }

        // What the Harvest job calls after taking from one (NPCManager.cs:6249),
        // verbatim: the herb and mushroom farms redraw their slot, the fish trap its
        // catch; the hive and the poultry farm are called nothing.
        internal static void AfterHarvest(ManagersScript mn, InventorySlot c, int slotIndex)
        {
            var info = c.GetComponent<ItemInfo>();
            try
            {
                switch (info != null ? info.itemKey : null)
                {
                    case "farm_herb_01":
                    case "farm_herb_02":
                    case "farm_mushroom_01":
                        mn.gameMN.FarmCheck(c, c.GetComponent<BreedInfo>(), slotIndex, false);
                        break;
                    case "trap_fish_01":
                        mn.gameMN.TrapLoad(c);
                        break;
                }
            }
            catch (Exception e)
            {
                Plugin.Log.LogWarning("[policy] harvest callback threw on " + (info != null ? info.itemKey : "?")
                    + " slot " + slotIndex + ": " + e);
            }
        }

        // What a BULK move may write at all - All in / Stack /
        // All out (the vicinity's and a container's own), the quick-stack sweep,
        // Ctrl+click's vicinity destination. They write the real slots and call
        // nothing after, so unlike a move by hand (AfterWrite, D39) they cannot
        // make a write to a breeding prop whole: the poultry farm's FarmCheck is
        // what spawns its chickens, and it swaps with whatever is on the cursor,
        // so calling it after a bulk move could not restore the state either.
        // The rule is to keep them out, not to call the callback. Storage only:
        // the engine's inert answer (chests, material stores, closets, the
        // workers' drop-boxes - the harvest box and the mine carry a breed type
        // nothing reads), a treasure once looted open, and a bench strip while
        // the custom grid keeps vanilla's bench branch dead (D52's condition).
        // Breeding props, racks and the other machines (the pig farm, the food
        // box, the well) are out.
        internal static bool BulkSafe(InventorySlot c)
        {
            if (c == null || c.slots == null || IsWrecked(c))
            {
                return false;
            }
            switch (EngineOf(c))
            {
                case Engine.Inert:
                    return true;
                case Engine.Bench:
                    return Settings.CustomGrid.Value;
                case Engine.Treasure:
                    var treasure = c.GetComponent<TreasureScript>();
                    return treasure != null && treasure.opened && treasure.unlocked && !treasure.isCollection;
            }
            return false;
        }

        internal static Family FamilyOf(InventorySlot c)
        {
            if (IsCharacterBag(c))
            {
                return IsBodyBag(c) ? Family.Bodies : Family.Bags;
            }
            switch (EngineOf(c))
            {
                case Engine.Breed:
                    return Family.Breeding;
                case Engine.Bench:
                    return Family.Benches;
                case Engine.Inert:
                    return c != null && c.type == InventorySlot.Type.Material
                        ? Family.Materials : Family.Chests;
            }
            return Family.Other;
        }

        // D41: what is worth SEEING, asked only after PoolEligible has said what
        // may be TOUCHED. Never the other way round, and never one call: a filter
        // that could widen the set would be a preference switching off a safety
        // gate.
        internal static bool FamilyShown(Family f)
        {
            return Mode(f) != FamilyMode.Hidden;
        }

        // Vanilla's own refusal, verbatim (PlayerMove.UseProp, PlayerMove.cs:793):
        // a prop that carries a DefenceInfo, has a life bar, and has run it out
        // is a wreck. UseProp skips the chest branch for one - no
        // SubInventoryLoad - and the build panel offers Repair alone, so the
        // contents are locked behind the repair. NOT an engine fact: a
        // wrecked chest is as inert as a whole one and a write to it would land,
        // which is exactly why the engine could not have caught it. It is the
        // game's rule about ACCESS, asked before any engine question and by the
        // focus as well as the pool - the two routes we have to what a
        // container holds, and a raid's consequence must hold on both.
        internal static bool IsWrecked(InventorySlot c)
        {
            if (c == null)
            {
                return false;
            }
            var info = c.GetComponent<ItemInfo>();
            if (info == null || info.lifeMax <= 0f || info.life > 0f)
            {
                return false;
            }
            return c.GetComponent<DefenceInfo>() != null;
        }

        // D38: ONE predicate for "may the pool hold and write this", asked
        // wherever a container is reached for. It replaces
        // `type == Material || type == None` in two files, which admitted every
        // breed prop in the game because they are all Type.None.
        //
        // This answers SAFETY only — whether a write can be made whole. What is
        // worth SEEING is a separate question and a user filter (D41); it may
        // narrow this set and may never widen it.
        internal static bool PoolEligible(InventorySlot c)
        {
            if (c == null || c.slots == null || c.slots.Length == 0)
            {
                return false;
            }
            // the game's access rule comes before its engine: a wreck is refused
            // whatever it would otherwise have been
            if (IsWrecked(c))
            {
                return false;
            }
            switch (EngineOf(c))
            {
                case Engine.Inert:
                    return true;
                // Admitted because AfterWrite runs the callback the panel's poll
                // would have run (D39). Without that this would be `false`, and
                // the pool would lose the cages and planters that are most of
                // the reason to look at what is around you.
                case Engine.Breed:
                    return true;
                // Fourteen callbacks, several of them coroutines entangled with
                // the vanilla panel's own widgets. Peeking at a drying rack is
                // not worth that surface.
                case Engine.Rack:
                    return false;
                // Ours to intercept, but NOT pool-safe: an unopened chest's loot
                // does not exist until TreasureSet runs, so the pool would draw
                // it empty and any write would be overwritten on first open.
                case Engine.Treasure:
                    return false;
                // Admitted, and the reasoning that kept them out is the reasoning
                // the filter dissolved. "Seventeen benches of ten slots is not a
                // view of what is around you, it is a second inventory screen" was
                // true and was an argument about DEFAULTS, not about safety - the
                // census found seventeen in one base. D43 gives defaults somewhere
                // to live, so ReachBenches ships Hidden and the answer stops
                // having to be compiled in.
                //
                // Safe for the same reason the focus panel has been writing them
                // all along: vanilla consumes a bench's strip from the mirror only
                // on a `craftPanelID != 0` branch, and the bench redirect holds that at 0. The
                // condition is CustomGrid, exactly as IsPlainStorage has it - with
                // the custom grid off, vanilla's bench panels are back and the
                // mirror is load-bearing again.
                case Engine.Bench:
                    return Settings.CustomGrid.Value;
                // The slots hold levels and launch state, not items: the Food Box
                // and the Well each have ONE slot whose itemLife is a fill gauge.
                case Engine.Prop:
                    return false;
            }
            return false;
        }

        // D39: WHERE WE TOOK THE PANEL AWAY, WE OWE ITS SIDE EFFECTS.
        //
        // Vanilla's `BreedInventory` coroutine watches the mirror grid and calls
        // one of these four whenever a slot changes. We draw the same container
        // without that panel, so the poll never runs and the write lands in the
        // slots with nothing acting on it — a cage that keeps animating an NPC
        // who is no longer in it, a planter holding a seed that never sprouts.
        //
        // Called AFTER the slot has changed, which is exactly how the game calls
        // them: each one reads the slot as it now is, tears down whatever was
        // under `pos_NN`, and rebuilds from what it finds. That makes them
        // idempotent and makes an emptied slot clear correctly — the teardown
        // happens before the early return that a non-matching item takes.
        //
        // The dispatch is BreedInventory's switch verbatim. Nothing here decides
        // anything; the game decides, and this only makes sure it is asked.
        internal static void AfterWrite(ManagersScript mn, InventorySlot container,
            int slotIndex)
        {
            if (mn == null || mn.gameMN == null || container == null
                || container.slots == null
                || slotIndex < 0 || slotIndex >= container.slots.Length)
            {
                return;
            }
            // A MACHINE, TOO (the milker, like the cage, has callbacks when its
            // inventory changes, and without them its animation does not update).
            // A rack we view is written through
            // vanilla's mirror while vanilla has it open, and its poll runs the
            // callback then - the caller passes only REAL slots, so that case never
            // reaches here. Held without vanilla (picked by Tab, kept past its end,
            // D153) a write lands in the real slot with no poll watching, and this
            // runs what the poll would have: RackInventory's switch, verbatim.
            if (IsViewedRack(container))
            {
                AfterRackWrite(mn, container, slotIndex);
                return;
            }
            var breed = container.GetComponent<BreedInfo>();
            if (breed == null || !PolledBreed(breed.breedType))
            {
                return;
            }
            // These reach deep into the game — instantiating prefabs, reparenting
            // live NPCs, teleporting them. A throw in there must not take the
            // click handler with it, because the slot has ALREADY moved by now
            // and losing the rest of the refresh would leave the window lying
            // about it.
            try
            {
                switch (breed.breedType)
                {
                    case BreedInfo.BreedType.Trap:
                        // whole-container: a trap has one slot and TrapLoad takes
                        // no index
                        mn.gameMN.TrapLoad(container);
                        break;
                    case BreedInfo.BreedType.Pet:
                        mn.gameMN.PetCheck(container, slotIndex, breed, false);
                        break;
                    case BreedInfo.BreedType.Planter:
                        mn.gameMN.PlanterCheck(container, slotIndex, false);
                        break;
                    case BreedInfo.BreedType.Egg:
                    case BreedInfo.BreedType.Mushroom:
                    case BreedInfo.BreedType.Beehive:
                    case BreedInfo.BreedType.Herb:
                        mn.gameMN.FarmCheck(container, breed, slotIndex, false);
                        break;
                }
            }
            catch (Exception e)
            {
                Plugin.Log.LogWarning("[policy] " + breed.breedType
                    + " callback threw on slot " + slotIndex + ": " + e);
            }
        }

        // InventoryManager.RackInventory's dispatch (InventoryManager.cs:992),
        // verbatim - the coroutines started on the same manager vanilla starts them on
        private static void AfterRackWrite(ManagersScript mn, InventorySlot rack, int j)
        {
            GameManager g = mn.gameMN;
            InventoryManager inv = mn.inventory;
            try
            {
                switch (rack.type)
                {
                    case InventorySlot.Type.Rack: g.RackCheck(rack, j); break;
                    case InventorySlot.Type.BodyRack: g.BodyRackCheck(rack, j); break;
                    case InventorySlot.Type.GlassTank: g.GlassTankCheck(rack, j); break;
                    case InventorySlot.Type.ShowCase: g.ShowCaseCheck(rack, j); break;
                    case InventorySlot.Type.Pole: inv.StartCoroutine(g.PoleCheck(rack, j)); break;
                    case InventorySlot.Type.Toilet: inv.StartCoroutine(g.ToiletCheck(rack, j)); break;
                    case InventorySlot.Type.Table: g.TableCheck(rack, j); break;
                    case InventorySlot.Type.Capsule: inv.StartCoroutine(g.CapsuleCheck(rack)); break;
                    case InventorySlot.Type.Restrain: inv.StartCoroutine(g.RestrainCheck(rack, j)); break;
                    case InventorySlot.Type.Milk:
                        if (j == 0) { inv.StartCoroutine(g.MilkCheck(rack)); }
                        break;
                    case InventorySlot.Type.Dye: g.DyeBenchCheck(rack); break;
                    case InventorySlot.Type.Picture: g.PictureFrameCheck(rack); break;
                    case InventorySlot.Type.ItemStand: g.ItemStandSet(rack, j); break;
                    case InventorySlot.Type.Core: g.CoreGenerate(rack, generate: false); break;
                }
            }
            catch (Exception e)
            {
                Plugin.Log.LogWarning("[policy] " + rack.type + " callback threw on slot " + j + ": " + e);
            }
        }
    }
