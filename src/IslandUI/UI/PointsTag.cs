using TMPro;
using UnityEngine;
using UnityEngine.UI;

namespace IslandUI.UI
{
    // POINTS TO SPEND (available skill points get an indicator in the sheets and on the
    // sheet activation button). The close button's enamel on a tag that says how many:
    // jade with a spark for the skill level's points, which are yours alone; cerulean
    // with an arrow for attribute points, which everyone has - each the colour of its
    // level's EXP bar, so the two align. It hangs on the page's tab,
    // replaces the page's "points" label, and sits on the chip that opens the sheet - the
    // Player dock's for you, the target's dock's for anyone else.
    //
    // Art generated by a dev script: the body is a 9-slice, since the number is
    // the game's type and the tag grows with it; the glyph is its own mark. The number is
    // cream outlined in ink as the close's X is - the one text in this UI that wears an
    // outline, because it is part of an enamel badge rather than type on a surface.
    internal sealed class PointsTag
    {
        // Mood: the ruby tag with a bang, counting the unhappy (the mood census)
        public enum Kind { Skill, Attribute, Mood }

        public const float Height = 8f;           // on a tab or a chip; the page's label is 9
        // the anime HUD's pills at the board's sizes: 31 of its pixels on the docks,
        // 36 on the player panel (its "35")
        public const float DockPill = 6.4f, PanelPill = 7.2f;
        private static readonly Color Ink = new Color32(32, 21, 14, 255);
        private static readonly Color Cream = new Color32(248, 235, 205, 255);

        public readonly RectTransform Rect;
        public float Width { get; private set; }
        public float H { get; private set; }

        private readonly Image _body;
        private readonly Image _glyph;
        private readonly TextMeshProUGUI _text;
        private int _kind = -1;
        private string _drew;
        private float _measured;
        private bool _outlined;
        // the anime HUD's docks: the board's enamel count pill, a "+" for points
        // and the bare count for the unhappy, no glyph (art/hud-anime-v1)
        private readonly bool _anime;

        private PointsTag(Transform parent, string name, bool anime)
        {
            _anime = anime;
            _body = Theme.KitImage(parent, name, "kit_tag_cerulean", 11, Color.white);
            Rect = _body.rectTransform;
            _glyph = Theme.KitImage(Rect, "Glyph", "kit_glyph_up", 0, Color.white);
            _text = Theme.MakeKitText(Rect, "Points", 5f, Cream, TextAlignmentOptions.MidlineLeft, bold: true);
            _text.fontStyle = FontStyles.Bold;   // the game's face has no bold of its own
            _text.enableWordWrapping = false;
            _text.overflowMode = TextOverflowModes.Overflow;
            _text.raycastTarget = false;
            Rect.gameObject.SetActive(false);
        }

        public static PointsTag Create(Transform parent, string name, bool anime = false)
        {
            return new PointsTag(parent, name, anime);
        }

        public bool Shown { get { return Rect.gameObject.activeSelf; } }

        // Draws the tag for `text` at height `h` and shows it; the owner places Rect
        // from Width and H.
        public void Show(Kind kind, string text, float h = Height)
        {
            if (_anime && kind != Kind.Mood && !text.StartsWith("+"))
            {
                text = "+" + text;
            }
            if ((int)kind != _kind && _anime)
            {
                _kind = (int)kind;
                AnimePieces.Sliced(_body, kind == Kind.Skill ? "badge_jade" : kind == Kind.Mood ? "badge_ruby" : "badge_cerulean",
                    new Vector4(28, 28, 28, 28));
                _glyph.enabled = false;
                _text.color = Color.white;
                // the board's pills carry the HUD's serif, white on the enamel
                TMP_FontAsset serif = InventoryWindow.HudStrongFont;
                if (serif != null && _text.font != serif)
                {
                    _text.font = serif;
                    _text.fontStyle = FontStyles.Normal;
                    _outlined = false;
                }
            }
            else if ((int)kind != _kind)
            {
                _kind = (int)kind;
                Theme.KitSkin(_body, kind == Kind.Skill ? "kit_tag_jade"
                    : kind == Kind.Mood ? "kit_tag_ruby" : "kit_tag_cerulean", 11);
                Theme.KitSkin(_glyph, kind == Kind.Skill ? "kit_glyph_spark"
                    : kind == Kind.Mood ? "kit_glyph_bang" : "kit_glyph_up", 0);
            }
            Outline();
            // active before measuring: a text that has never been awake measures nothing
            if (!Rect.gameObject.activeSelf)
            {
                Rect.gameObject.SetActive(true);
            }
            // A text measured before its row was live measures wrong - too narrow, the
            // number without its word - so the width is checked again while it shows
            bool live = _text.isActiveAndEnabled;
            if (live && _drew == text && Mathf.Abs(_text.preferredWidth - _measured) > 0.5f)
            {
                _drew = null;
            }
            if (text != _drew || !Mathf.Approximately(h, H))
            {
                H = h;
                // the board's pill: figures half its height (Noto's are .714 em), the
                // pill 1.87 heights long for "+80"
                float size = _anime ? h * 0.72f : h * 0.74f;
                if (_text.text != text) { _text.text = text; }
                _text.fontSize = size;
                float tw = live ? _text.GetPreferredValues(text, 200f, h).x : 0f;
                _drew = live && tw > 0.5f ? text : null;
                if (_drew == null)
                {
                    tw = size * 0.6f * text.Length;   // a guess, until it can measure
                }
                _measured = tw;
                float g = _anime ? 0f : h * 0.6f;
                float pad = _anime ? h * 0.34f : h * 0.26f;
                float gap = _anime ? 0f : h * 0.06f;
                if (_anime) { _body.pixelsPerUnitMultiplier = 88f / h; }
                Width = Mathf.Round((pad * 2f + g + gap + tw) * 2f) * 0.5f;
                Rect.sizeDelta = new Vector2(Width, h);
                // the enamel's middle sits a little above the rect's: the shadow is below
                float mid = h * 0.47f;
                Theme.Place(_glyph, pad, mid - g * 0.5f, g, g);
                Theme.Place(_text, pad + g + gap, mid - h * 0.5f, tw + 2f, h);
            }
        }

        public void Hide()
        {
            if (Rect.gameObject.activeSelf)
            {
                Rect.gameObject.SetActive(false);
            }
        }

        // the ink around the number: the material is instanced by fontMaterial, so this
        // reaches no other text. Deferred until the face exists (Theme.FlattenType).
        private void Outline()
        {
            if (_outlined || _text.font == null || _text.fontSharedMaterial == null)
            {
                return;
            }
            Material m = _text.fontMaterial;
            if (m == null)
            {
                return;
            }
            _outlined = true;
            m.EnableKeyword(ShaderUtilities.Keyword_Outline);
            // the serif carries its own weight: a thinner edge, no dilation
            m.SetFloat(ShaderUtilities.ID_FaceDilate, _anime ? 0.05f : 0.22f);
            m.SetFloat(ShaderUtilities.ID_OutlineWidth, _anime ? 0.22f : 0.34f);
            m.SetColor(ShaderUtilities.ID_OutlineColor, Ink);
            _text.UpdateMeshPadding();
        }
    }
}
